"""
WritingAgent - Phase Beta-Search Upgrade

Content generation agent with structured output templates.
Supports report, article, and analysis formats.
"""

import time
from dataclasses import dataclass, field
from datetime import datetime, timezone

from app.agents.base import BaseAgent, AgentConfig, AgentResponse, AgentType, AgentStatus
from app.utils.logger import get_logger

logger = get_logger(__name__)

OUTPUT_TEMPLATES = {
    "report": """# {title}

## Executive Summary

{summary}

## Background

{background}

## Data Analysis

{analysis}

## Trends

{trends}

## Risks & Considerations

{risks}

## Recommendations

{recommendations}

---

*Generated by WriterAgent | Sources: {source_count}*
""",
    "article": """# {title}

{body}

## Conclusion

{conclusion}

---

*Generated by WriterAgent | Sources: {source_count}*
""",
    "analysis": """# Analysis: {title}

## Problem Statement

{problem}

## Facts & Evidence

{facts}

## Analysis

{analysis}

## Judgment

{judgment}

---

*Generated by WriterAgent | Sources: {source_count}*
""",
}


class WritingAgent(BaseAgent):
    """Content generation Agent with structured templates."""

    def __init__(self, llm_provider=None):
        self._llm = llm_provider
        config = AgentConfig(
            id="writing",
            name="writing",
            type=AgentType.WRITING,
            capabilities=["markdown_generate", "report_generate", "content_write", "article_gen", "script_gen", "copywriting"],
            extra={"description": "Generate articles, reports, and structured content"},
        )
        super().__init__(config)
        self._status = AgentStatus.ONLINE

    async def chat(self, message: str, context: dict | None = None) -> str:
        return f"[WritingAgent] Writing request: {message}"

    async def execute_task(self, task_input: dict) -> AgentResponse:
        """
        Execute writing task.
        Input: {"task": str, "research_result": dict, "output_type": str, "context": dict}
        Output: AgentResponse with generated content
        """
        task = task_input.get("task", "")
        research_result = task_input.get("research_result", {})
        output_type = task_input.get("output_type", "report")

        start = time.monotonic()

        sources = research_result.get("sources", [])
        documents = research_result.get("extracted_documents", research_result.get("sources", []))
        source_count = len(sources)

        # Build context from research results
        source_texts = []
        for doc in documents:
            title = doc.get("title", "")
            snippet = doc.get("snippet", doc.get("content", ""))
            if title and snippet:
                source_texts.append(f"- {title}: {snippet[:300]}")
        source_summary = "\n".join(source_texts[:15])

        # Generate content based on template
        template = OUTPUT_TEMPLATES.get(output_type, OUTPUT_TEMPLATES["report"])
        content = template.format(
            title=f"Research Report: {task}",
            summary=f"This report presents findings on '{task}' based on analysis of {source_count} sources.",
            background=f"The topic '{task}' has been researched using web sources and information extraction.\n\nKey sources identified:\n{source_summary}",
            analysis=f"Analysis of collected information on '{task}' reveals several key patterns and insights from the {source_count} sources reviewed.",
            trends=f"Based on current information, the following trends are observed for '{task}':\n\n1. Growing interest and development\n2. Expanding application areas\n3. Increasing adoption across sectors",
            risks=f"Key risks to consider:\n\n1. Rapid technological change\n2. Market competition\n3. Regulatory uncertainties",
            recommendations=f"Based on this research, the following recommendations are made:\n\n1. Monitor developments closely\n2. Invest in relevant capabilities\n3. Stay informed about regulatory changes",
            body=f"# {task}\n\nThis article explores {task} based on research from {source_count} sources.\n\n## Key Findings\n\n{source_summary}\n\n## Discussion\n\nThe collected information provides a comprehensive view of {task}.",
            conclusion=f"In conclusion, {task} represents an important area worthy of continued attention and investment.",
            problem=f"The core question: what is the current state and outlook for {task}?",
            facts=f"Collected evidence from {source_count} sources:\n\n{source_summary}",
            judgment=f"Assessment: {task} shows strong potential based on the available evidence.",
            source_count=source_count,
        )

        llm_content = await self._generate_with_llm(task, research_result, output_type, source_summary)
        if llm_content:
            content = llm_content

        # Build citation list
        citations = research_result.get("citations", [])
        if not citations:
            for src in sources:
                citations.append({"title": src.get("title", ""), "url": src.get("url", "")})

        duration = int((time.monotonic() - start) * 1000)

        return AgentResponse(
            success=True,
            data={
                "agent": "writing",
                "title": f"Research Report: {task}",
                "content": content,
                "output_type": output_type,
                "source_count": source_count,
                "citations": citations,
                "word_count": len(content.split()),
                "summary": f"Generated {output_type} with {source_count} sources",
            },
            agent_id=self.id,
            duration_ms=duration,
            metadata={
                "output_type": output_type,
                "source_count": source_count,
                "template": output_type,
                "llm_used": bool(llm_content),
            },
        )

    def get_capabilities(self) -> list[str]:
        caps = super().get_capabilities()
        if not caps:
            caps = ["markdown_generate", "report_generate", "content_write", "article_gen", "script_gen", "copywriting"]
        return caps
